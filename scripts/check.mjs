assert.equal(escapeHTML('<img src=x onerror="alert(1)">'),'&lt;img src=x onerror=&quot;alert(1)&quot;&gt;');
for(const payload of ['javascript:alert(1)','data:text/html,test','http://evil.example/file.pdf','https://user:password@example.com/','file:///etc/passwd'])assert.equal(safeResumeUrl(payload,'https://portfolio.example'),null,payload);
assert.equal(safeResumeUrl('./assets/resume.pdf','https://portfolio.example/sub/'),'https://portfolio.example/sub/assets/resume.pdf');
assert.equal(safeResumeUrl('https://example.com/resume.pdf','https://portfolio.example'),'https://example.com/resume.pdf');
assert.match(contentSecurityPolicy,/frame-ancestors 'none'/);
assert.match(contentSecurityPolicy,/connect-src 'none'/);
assert.ok(!contentSecurityPolicy.includes('unsafe-inline')&&!contentSecurityPolicy.includes('unsafe-eval'));
assert.ok(!html.match(/<script[^>]*src="https?:/));
assert.ok(!html.match(/\son\w+\s*=/i));
const css=await readFile(new URL('styles.css',root),'utf8');
assert.ok(!css.includes('@import'));
console.log('PASS: escaped HTML, blocked unsafe résumé URLs, restrictive CSP, and no remote scripts/fonts.');

assert.equal(resumePreviewUrl('https://drive.google.com/file/d/1GoPXCV1WW5Ffowm1sWOl2W6nOedeeHbt/view?usp=sharing','https://portfolio.example'),'https://drive.google.com/file/d/1GoPXCV1WW5Ffowm1sWOl2W6nOedeeHbt/preview');
