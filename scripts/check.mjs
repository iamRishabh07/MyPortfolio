import assert from 'node:assert/strict';
import {readFile,access} from 'node:fs/promises';
import {executeCommand} from '../terminal.js';
import {profile} from '../profile.js';
import {escapeHTML,safeResumeUrl,resumePreviewUrl} from '../security.js';
import {contentSecurityPolicy} from '../security-policy.mjs';
const root=new URL('../',import.meta.url);
for(const command of ['help','whoami','skills','experience','projects','education','awards','contact','github','date'])assert.ok(executeCommand(command).text.length>10,command);
assert.equal(executeCommand('project argos').id,'argos');
assert.match(executeCommand('project missing').text,/Available IDs/);
assert.equal(executeCommand('clear').action,'clear');
assert.equal(executeCommand('theme').action,'theme');
assert.equal(executeCommand('resume').action,'resume');
assert.match(executeCommand('resume').text,profile.resumeUrl?/Résumé:/ : /coming soon/);
assert.match(executeCommand('unknown command').text,/Command not found/);
assert.equal(executeCommand('echo <script>alert(1)</script>').text,'<script>alert(1)</script>');
assert.equal(executeCommand('   ').text,'');
assert.match(executeCommand('WHOAMI').text,/Rishabh/);
const html=await readFile(new URL('index.html',root),'utf8');
for(const match of html.matchAll(/(?:src|href)="([^"#][^"]*)"/g)){const value=match[1];if(!/^(https?:|mailto:|data:)/.test(value))await access(new URL(value,root))}
